/**
 * Returns an SVG string for the requested icon.
 * @param {string} name - Name of the icon
 * @param {string|object} classNameOrAttrs - Optional CSS classes or attributes object
 * @param {object} attrs - Optional attributes like aria-label, size
 */
export function getIcon(name, classNameOrAttrs = '', attrs = {}) {
    let className = '';
    let resolvedAttrs = attrs || {};
    if (typeof classNameOrAttrs === 'object' && classNameOrAttrs !== null) {
        resolvedAttrs = classNameOrAttrs;
        className = resolvedAttrs.className || '';
    } else if (typeof classNameOrAttrs === 'string') {
        className = classNameOrAttrs;
    }

    const iconBody = ICONS[name] || ICONS['help-circle'];
    const size = resolvedAttrs.size || 18;
    const isAriaHidden = resolvedAttrs['aria-label'] ? '' : 'aria-hidden="true"';
    const ariaLabel = resolvedAttrs['aria-label'] ? `aria-label="${resolvedAttrs['aria-label']}" role="img"` : '';

    const classes = `ss-icon ss-icon-${name} ${className}`.trim();
    return `<svg class="${classes}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" ${isAriaHidden} ${ariaLabel}>${iconBody}</svg>`;
}

export function renderIcon(name, className = '', attrs = {}) {
    return getIcon(name, className, attrs);
}

